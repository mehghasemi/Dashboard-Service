import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'
import {createRequire} from 'node:module'
import {fileURLToPath,pathToFileURL} from 'node:url'
const root=path.dirname(fileURLToPath(import.meta.url))
// Pass the directory containing the available Playwright package; no installation.
const require=createRequire(path.join(path.resolve(process.argv[2]||root),'package.json'))
const {chromium}=require('playwright')
const output=path.resolve(root,'../outputs/design-standard')
await fs.mkdir(output,{recursive:true})
const browser=await chromium.launch({headless:true,...(process.argv[3]?{executablePath:path.resolve(process.argv[3])}:{})})
try{
  const page=await browser.newPage({viewport:{width:1440,height:1060},deviceScaleFactor:1})
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  const external=[];page.on('request',request=>{if(/^https?:/.test(request.url()))external.push(request.url())})
  await page.goto(pathToFileURL(path.join(root,'preview.html')).href)
  await page.evaluate(()=>document.fonts.ready)
  assert.equal(await page.evaluate(()=>document.fonts.check('14px Dana')),true)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  assert.equal(await page.locator('#account-rows tr:visible').count(),3)
  await page.screenshot({path:path.join(output,'desktop.png'),fullPage:true})
  await page.locator('#settings-trigger').click()
  assert.equal(await page.locator('#settings-popover').isVisible(),true)
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('#settings-trigger').evaluate(node=>node===document.activeElement),true)
  await page.getByRole('button',{name:'اکانت جدید',exact:true}).click()
  assert.equal(await page.locator('#record-dialog').evaluate(node=>node.open),true)
  await page.locator('#record-dialog input[name=name]').fill('نمونه آزمایش')
  await page.getByRole('button',{name:'ثبت نمونه',exact:true}).click()
  assert.equal(await page.locator('#record-dialog').evaluate(node=>node.open),false)
  await page.locator('#toast').evaluate(node=>node.hidden=true)
  await page.locator('#account-search').fill('آفتاب')
  assert.equal(await page.locator('#account-rows tr:visible').count(),1)
  await page.locator('#account-search').fill('وجود ندارد')
  assert.equal(await page.locator('#search-empty').isVisible(),true)
  await page.locator('#reset-search').click()
  assert.equal(await page.locator('#account-rows tr:visible').count(),3)
  await page.locator('#review-components').click()
  assert.equal(await page.locator('#icon-gallery .icon-cell').count(),18)
  await page.locator('#state-picker').selectOption('error')
  await page.locator('#retry-state').click()
  assert.equal(await page.locator('#data-state').getAttribute('aria-busy'),'true')
  await page.waitForFunction(()=>document.getElementById('state-picker').value==='empty')
  await page.screenshot({path:path.join(output,'components.png'),fullPage:true})
  await page.locator('#review-rules').click()
  await page.screenshot({path:path.join(output,'rules.png'),fullPage:true})
  await page.locator('#review-workspace').click()
  await page.setViewportSize({width:390,height:844})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true})
  await page.locator('#open-menu').click()
  assert.equal(await page.locator('#app-sidebar').isVisible(),true)
  assert.equal(await page.locator('.app-main').evaluate(node=>node.inert),true)
  await page.screenshot({path:path.join(output,'mobile-menu.png'),fullPage:true})
  await page.keyboard.press('Shift+Tab')
  assert.equal(await page.locator('#app-sidebar button:visible').last().evaluate(node=>node===document.activeElement),true)
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('#open-menu').evaluate(node=>node===document.activeElement),true)
  assert.equal(await page.locator('.app-main').evaluate(node=>node.inert),false)
  await page.locator('#review-components').click()
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await page.getByRole('button',{name:'پنجرهٔ تنظیمات',exact:true}).click()
  assert.equal(await page.locator('#settings-dialog').isVisible(),true)
  await page.screenshot({path:path.join(output,'mobile-dialog.png'),fullPage:true})
  await page.keyboard.press('Escape')
  await page.locator('#review-rules').click()
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  for(const width of [320,360,768,1024]){
    await page.setViewportSize({width,height:844})
    for(const view of ['workspace','components','rules']){
      await page.locator('#review-'+view).click()
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`${view} overflow at ${width}`)
    }
  }
  const missing=await page.evaluate(()=>[...document.querySelectorAll('use')].filter(node=>!document.getElementById(node.getAttribute('href')?.slice(1))).map(node=>node.getAttribute('href')))
  assert.deepEqual(missing,[])
  assert.deepEqual(errors,[])
  assert.deepEqual(external,[])
  const result={ok:true,desktop:'1440×1060',mobile:'390×844',checks:['local fonts','icon references','no external requests','no console errors','no page overflow','menus and focus','dialog submit and Escape','search and empty state','tabs','retry state'],screenshots:output}
  await fs.writeFile(path.join(output,'verification.json'),JSON.stringify(result,null,2)+'\n')
  console.log(JSON.stringify(result,null,2))
}finally{await browser.close()}
